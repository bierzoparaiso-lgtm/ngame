const availableLanguages = Object.keys(translations);

function getText(key, lang) {
    const targetLang = translations[lang] ? lang : 'EN';
    return translations[targetLang][key] || translations['EN'][key] || key;
}

function registerLanguage(code, translationsObject) {
    const upperCode = code.toUpperCase();
    translations[upperCode] = translationsObject;
    if (!availableLanguages.includes(upperCode)) {
        availableLanguages.push(upperCode);
    }
    window.dispatchEvent(new CustomEvent('languagesUpdated'));
}
